function norm(s) {
  return String(s || "").trim().toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "");
}
const BY_NORM = new Map(Object.entries(MEDIA_IDS).map(([k, v]) => [norm(k), v]));

/** [inicio, final] del movimiento, o null si no hay fotos para ese ejercicio. */
export function getExerciseFrames(name) {
  const id = BY_NORM.get(norm(name));
  return id ? [`${CDN}/${id}/0.jpg`, `${CDN}/${id}/1.jpg`] : null;
}

